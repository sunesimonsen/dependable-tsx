const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const capitalize = (val) =>
  String(val).charAt(0).toUpperCase() + String(val).slice(1);

const elementData = {};

for (const tag of Object.keys(elementValidationData)) {
  elementData[tag] = {};

  elementData[tag] = { ...elementValidationData[tag] };

  const names = htmlElementAttributes[tag] || [];
  if (!elementData[tag].attributes && names.length > 0) {
    elementData[tag].attributes = {};
  }

  for (const name of names) {
    if (!(name in elementData[tag].attributes)) {
      if (name === "autofocus") {
        elementData[tag].attributes[name] = { boolean: true };
      } else {
        elementData[tag].attributes[name] = {};
      }
    }
  }
}

const deprecatedElements = new Set(["rb", "rtc", "search"]);

function isDeprecated(element) {
  if (element.deprecated) return true;

  if (deprecatedElements.has(element.tag)) {
    return true;
  }

  return false;
}

const elements = Object.keys(elementData)
  .map((tag) => ({ type: "tag", tag, ...elementData[tag] }))
  .filter(({ tag }) => tag !== "*" && !tag.startsWith("svg:"))
  .filter((element) => !isDeprecated(element));

const getAttributes = (element) =>
  Object.entries(element.attributes || {}).filter(
    ([attribute, spec]) => attribute !== "style" && !spec.deprecated,
  );

let output = `/// <reference lib="dom" />
// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
// This file was generated by generate-attribute-types.js using HTML element
// data from the html-validate module.

interface Stringable {
  toString(): string;
}

export type RefCallback<T extends Element> = (element: T) => void;

`;

output += `export interface EventAttributes {\n`;

for (const eventHandler of eventHandlers) {
  output += `  ${eventHandler}?: GlobalEventHandlers["${eventHandler.toLowerCase()}"];\n`;
  if (!eventHandler.endsWith("Capture")) {
    output += `  ${eventHandler}Capture?: GlobalEventHandlers["${eventHandler.toLowerCase()}"];\n`;
  }
}

output += `}\n\n`;

output += `export interface AriaAttributes {\n`;

for (const ariaAttribute of ariaAttributes) {
  output += `  "${ariaAttribute}"?: string;\n`;
}

output += `}\n\n`;

function outputAttributes(attributes) {
  for (const [attribute, rules] of attributes) {
    if (rules.deprecated) continue;
    const optional = rules.required ? "" : "?";
    let type = "string";
    if (rules.boolean) {
      type = "boolean";
    } else if (rules.enum) {
      if (rules.enum[0] instanceof RegExp) {
        type = "string";
      } else if (rules.enum[0] === "/\\d+/") {
        type = "number | string";
      } else if (rules.enum[0].startsWith("/")) {
        type = "string";
      } else {
        type = rules.enum.map((e) => `"${e}"`).join(" | ");
      }
    }

    output += `  "${attribute}"${optional}: ${type};\n`;
  }
}

function getElement(tag) {
  switch (tag) {
    case "svg":
      return "SVGElement";
    case "math":
      return "MathMLElement";
    default:
      return `HTMLElementTagNameMap["${tag}"]`;
  }
}

function outputInterface(element) {
  const interfaceName = `Html${capitalize(element.tag)}Attributes`;
  output += `export interface ${interfaceName} extends GlobalHtmlAttributes {\n`;
  output += `  ref?: RefCallback<${getElement(element.tag)}>;\n`;
  if (!element.void) {
    output += `  children?: JSX.Nodes;\n`;
  }

  outputAttributes(getAttributes(element));

  output += `}\n\n`;
}

output += `export interface GlobalHtmlAttributes extends EventAttributes, AriaAttributes {\n`;
output += `  "style"?: string | Stringable | Partial<CSSStyleDeclaration>;\n`;
output += `  "className"?: string | Stringable;\n`;

outputAttributes(getAttributes(elementData["*"]));

output += `}\n\n`;

for (const element of elements) {
  outputInterface(element);
}

output += `export type HtmlAttributesByTag = {\n`;
for (const element of elements) {
  output += `  "${element.tag}":  ${`Html${capitalize(element.tag)}Attributes`};\n`;
}
output += `}\n\n`;

const outPath = path.join(__dirname, "../src/HtmlAttributes.ts");

const formattedOutput = await prettier.format(output, {
  parser: "typescript",
});
writeFileSync(outPath, formattedOutput, "utf8");
